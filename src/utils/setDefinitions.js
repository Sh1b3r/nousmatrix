export function resolveRelicSetInfo(r, lang = "ru") {
  if (!r) return null;
  const isRu = lang === "ru";
  const name = (r.name || "").toLowerCase().trim();
  const sName = (r.set_name || "").toLowerCase().trim();
  let sId = String(r.set_id || "").trim();

  // If set_id is empty or unknown, extract 3-digit setId from 5-digit/6-digit relic id/tid (e.g. 63295 -> 329)
  if (!sId || sId === "0" || sId === "unknown") {
    const rawId = String(r.id || r.tid || "").trim();
    if (rawId.length >= 5) {
      sId = rawId.slice(1, 4);
    } else if (rawId.length === 4) {
      sId = rawId.slice(0, 3);
    }
  }

  if (sId) {
    const byId = SET_DEFINITIONS.find((def) => def.ids.includes(sId) || def.id === sId);
    if (byId) {
      return {
        matched: true,
        name: isRu ? byId.nameRu : byId.nameEn,
        def: byId,
        icon: byId.icon
      };
    }
  }
  for (const def of SET_DEFINITIONS) {
    if (sName && (def.nameRu.toLowerCase() === sName || def.nameEn.toLowerCase() === sName)) {
      return {
        matched: true,
        name: isRu ? def.nameRu : def.nameEn,
        def,
        icon: def.icon
      };
    }
    if (name && (def.keywords.includes(name) || def.keywords.some((k) => k.length >= 4 && name.includes(k)))) {
      return {
        matched: true,
        name: isRu ? def.nameRu : def.nameEn,
        def,
        icon: def.icon
      };
    }
    if (sName && def.keywords.some((k) => k.length >= 4 && (sName.includes(k) || k.includes(sName)))) {
      return {
        matched: true,
        name: isRu ? def.nameRu : def.nameEn,
        def,
        icon: def.icon
      };
    }
  }
  return {
    matched: false,
    name: isRu ? sId ? `Сет #${sId}` : "Неизвестный сет" : r.set_name || (sId ? `Set #${sId}` : "Unknown Set"),
    def: null,
    icon: r.icon
  };
}
